"""生成图5-2 异常与状态联动活动/泳道图（PNG + SVG）。

运行：python 生成图5-2异常与状态联动泳道图.py
依据：正文5.1、5.4；BR07、BR09、BR12、BR13、BR15、BR19；ST-B-09、ST-B-12、ST-B-16—ST-B-21。
"""
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from 绘图工具 import Diagram, NOTE_FILL, MUTED, wrap, STROKE  # noqa: E402

BUY = (60, 370)      # 买方泳道
SELL = (430, 740)    # 卖方泳道
ADMIN = (800, 1110)  # 管理员泳道
SYS = (1160, 1470)   # 系统泳道


def build():
    g = Diagram(1500, 1960)
    lanes = [(40, 400, "买方"), (410, 770, "卖方"), (780, 1140, "管理员"),
             (1150, 1500, "系统（物品／订单）")]

    # 泳道分隔线与表头
    for x, _, _ in lanes[1:]:
        g.line([(x, 110), (x, 1930)], arrow=False, dash=True, width=2, color="#94A3B8")
    for x1, x2, name in lanes:
        g.box((x1, 40, x2, 105), name, size=26, fill="#E2E8F0", pad=10)

    # 节点
    g.box((SYS[0], 130, SYS[1], 235), "异常入口：取消、催办\n或交付分歧请求", 22, pad=10)
    g.box((SYS[0], 265, SYS[1], 370), "核验身份、归属与阶段\n（BR09、10、14）", 22, pad=10)
    g.diamond(1315, 475, 330, 150, "已有登记、已报告\n交付或争议受理？", size=22)
    g.box((SELL[0], 580, SELL[1], 680), "当事人（买／卖任一方）\n声明未交付、提交原因", 22, pad=10)
    g.box((SYS[0], 690, SYS[1], 800), "订单→已取消，释放占用\n（ST-B-16／18）", 22, pad=10)
    g.box((SYS[0], 830, SYS[1], 940), "重检审核、隐藏、撤下、成交\n与卖方资格；满足→在售\n（ST-B-09），否则不可交易", 22, pad=10)
    g.end(1315, 975)
    g.text((1345, 975), "结束", 22, anchor="lm", color=MUTED)

    g.box((ADMIN[0], 720, ADMIN[1], 830), "当事人提出后受理：\n记录理由与证据，保留\n阶段及占用（BR15）", 22, pad=10)
    g.box((ADMIN[0], 860, ADMIN[1], 970), "核查交付、补证与\n关联举报（BR15、16）", 22, pad=10)
    g.diamond(955, 1070, 300, 150, "能否继续履约？", size=22)

    g.box((SELL[0], 1170, SELL[1], 1280), "卖方补登记交付\n（ST-B-17）", 22, pad=10)
    g.box((BUY[0], 1310, BUY[1], 1420), "买方本人确认收到\n（ST-B-19）", 22, pad=10)
    g.box((SYS[0], 1310, SYS[1], 1420), "订单→已完成；\n物品→已成交（ST-B-19）", 22, pad=10)
    g.end(1315, 1450)
    g.text((1345, 1450), "结束", 22, anchor="lm", color=MUTED)

    g.box((ADMIN[0], 1170, ADMIN[1], 1280), "记录依据并异常终止\n（BR19）", 22, pad=10)
    g.box((SYS[0], 1490, SYS[1], 1600), "订单→已异常终止，\n释放占用；物品仍不可售\n（ST-B-21）", 22, pad=10)
    g.box((SELL[0], 1630, SELL[1], 1740), "核实归属后退还或\n显式重发（BR19）", 22, pad=10)
    g.box((SYS[0], 1770, SYS[1], 1880), "物品→待审，重新审核\n（ST-B-12）", 22, pad=10)
    g.end(1315, 1918)
    g.text((1345, 1918), "结束", 22, anchor="lm", color=MUTED)

    # 控制流
    g.line([(1315, 235), (1315, 265)])
    g.line([(1315, 370), (1315, 400)])
    g.line([(1315, 550), (1315, 620), (740, 620)])              # 否
    g.text((1332, 580), "否", 23, anchor="lm")
    g.line([(1150, 475), (955, 475), (955, 720)])               # 是
    g.text((1000, 452), "是", 23, anchor="lm")
    g.line([(585, 680), (585, 700), (1160, 700)])
    g.line([(1315, 800), (1315, 830)])
    g.line([(1315, 940), (1315, 957)])
    g.line([(955, 830), (955, 860)])
    g.line([(955, 970), (955, 995)])
    g.line([(805, 1070), (585, 1070), (585, 1170)])             # 是
    g.text((700, 1046), "是", 23)
    g.line([(955, 1145), (955, 1170)])                          # 否
    g.text((975, 1158), "否", 23, anchor="lm")
    g.line([(585, 1280), (585, 1340), (370, 1340)])
    g.line([(370, 1390), (1160, 1390)])
    g.line([(1315, 1420), (1315, 1432)])
    g.line([(900, 1280), (900, 1550), (1160, 1550)])
    g.line([(1315, 1600), (1315, 1620), (585, 1620), (585, 1630)])
    g.line([(585, 1740), (585, 1770), (1160, 1770)])
    g.line([(1315, 1880), (1315, 1900)])

    # 并行治理说明
    g.box((BUY[0], 160, BUY[1], 420), "", fill=NOTE_FILL, pad=14, color="#B45309")
    g.text((215, 192), "并行治理", 23)
    note = ("限制账户：拒绝新下单、\n新发布（BR12）；保留\n旧单必要权利。\n解封后仍须重检隐藏、\n撤下与成交状态\n（BR03、BR13）。")
    y = 228
    for para in note.split("\n"):
        for line in wrap(para, 20, 260):
            g.text((78, y), line, 20, anchor="lm")
            y += 29

    return g.save("图5-2_异常与状态联动泳道图")


if __name__ == "__main__":
    png, svg = build()
    print("已生成：", png.name, "、", svg.name)
