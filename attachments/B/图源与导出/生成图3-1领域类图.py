    g.text((1228, 916), "0..*", 23, bg=True, anchor="rm")
    g.text((1266, 916), "1", 23, bg=True)

    # 左下说明（左对齐逐行绘制）
    from 绘图工具 import wrap  # noqa: E402

    g.box((50, 730, 470, 1430), "", fill=NOTE_FILL, pad=16, color="#B45309")
