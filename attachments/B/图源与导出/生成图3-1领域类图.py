    g.class_box((50, 530, 450, 690), "会话", ["类型（物品咨询／订单）", "状态（进行／只读）"])
    g.class_box((550, 530, 950, 830), "订单",
                ["订单号", "当前阶段", "建立时间", "终止原因"])
    g.class_box((1050, 410, 1450, 610), "举报",
                ["举报对象类型、理由", "证据", "处理结果与回执"])
    g.class_box((1050, 650, 1450, 900), "处置记录",
                ["类型（审核/举报等）", "对象标识、操作者", "时间与原因", "处理结果"])
    g.class_box((550, 870, 950, 1070), "订单快照",
                ["物品描述", "约定价格", "买卖双方信息"])
    g.class_box((1050, 940, 1450, 1140), "履约争议", ["申请理由", "补证", "结论"])
    g.class_box((550, 1110, 950, 1310), "交付登记", ["登记人、登记时间", "交接说明", "关联订单"])
    g.class_box((1050, 1210, 1450, 1410), "评价", ["评价人", "评分与内容", "公开状态"])

    # 基数与角色标签
    g.text((470, 140), "1", 24, bg=True)
    g.text((530, 140), "1", 24, bg=True)
    g.text((964, 142), "1", 24, bg=True)
    g.text((1042, 142), "0..*", 24, bg=True, anchor="rm")
    g.text((1000, 190), "发布", 23, color=MUTED)
    g.text((594, 300), "1", 24, bg=True)
