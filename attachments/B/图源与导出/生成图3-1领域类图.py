    g.line([(1250, 940), (1250, 900)], arrow=False)                     # 争议—处置记录

    # 类框
    g.class_box((50, 60, 450, 260), "校园认证", ["认证状态", "材料版本", "审核结论"])
    g.class_box((550, 60, 950, 290), "账户", ["账户标识", "昵称", "账户状态（正常／受限）"])
    g.class_box((1050, 60, 1450, 350), "物品",
                ["标题、分类、描述", "价格（人民币元）", "图片",
                 "审核状态、生命周期状态", "隐藏标记"])
